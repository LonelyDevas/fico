// Builds lib/local/schema.generated.ts from the Supabase migrations in ../fico-api/supabase/migrations.
//
// The offline database (PGlite, Postgres in the browser) runs the very same tables, triggers and RPC
// functions as the server, so balances, bills, budgets and reports can't drift between the two.
// The output is committed because the Vercel build only sees this repo, not fico-api.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

import { createHash } from 'node:crypto'
import { join } from 'node:path'

const MIGRATIONS = join('..', 'fico-api', 'supabase', 'migrations')
const OUT = join('lib', 'local', 'schema.generated.ts')

if (!existsSync(MIGRATIONS)) {
  console.log('[local-schema] ../fico-api not found, keeping the committed lib/local/schema.generated.ts')
  process.exit(0)
}

// Server-only pieces: admin/staff tables, row level security, Supabase Storage, push subscriptions,
// account reset/delete and the admin dashboard (these touch auth.users and stay online-only).
const SKIP = [/^0010_/, /^0011_/, /^0024_/, /^0034_/, /^0039_/, /^0048_/]
// Statements the browser database can't or shouldn't run.
// is_maintenance_mode and the AI cache are server-only (maintenance table, finance_agent_cache).
const DROP_STATEMENT = [/pg_cron/i, /cron.schedule/i, /create extension/i, /is_maintenance_mode/i, /reports_top_category_today/i, /finance_agent_cache/i]

/** Splits SQL into statements, respecting $$ bodies, quotes and comments. */
export function splitSql(sql) {
  const out = []
  let cur = ''
  let i = 0
  let dollar = null
  while (i < sql.length) {
    const ch = sql[i]
    if (dollar) {
      if (sql.startsWith(dollar, i)) {
        cur += dollar
        i += dollar.length
        dollar = null
      } else {
        cur += ch
        i++
      }
      continue
    }
    if (ch === '-' && sql[i + 1] === '-') {
      while (i < sql.length && sql[i] !== '\n') i++
      continue
    }
    if (ch === '/' && sql[i + 1] === '*') {
      const end = sql.indexOf('*/', i + 2)
      i = end === -1 ? sql.length : end + 2
      continue
    }
    if (ch === "'") {
      let j = i + 1
      while (j < sql.length) {
        if (sql[j] === "'" && sql[j + 1] === "'") j += 2
        else if (sql[j] === "'") break
        else j++
      }
      cur += sql.slice(i, j + 1)
      i = j + 1
      continue
    }
    if (ch === '$') {
      const m = /^\$[A-Za-z_]*\$/.exec(sql.slice(i, i + 40))
      if (m) {
        dollar = m[0]
        cur += dollar
        i += dollar.length
        continue
      }
    }
    if (ch === ';') {
      if (cur.trim()) out.push(cur.trim())
      cur = ''
      i++
      continue
    }
    cur += ch
    i++
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

// DO $$ ... $$ blocks that only exist to schedule cron are dropped whole.
const statements = []
for (const file of readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort()) {
  if (SKIP.some((re) => re.test(file))) continue
  for (const stmt of splitSql(readFileSync(join(MIGRATIONS, file), 'utf8'))) {
    if (DROP_STATEMENT.some((re) => re.test(stmt))) continue
    statements.push(stmt)
  }
}

const header = `// GENERATED by scripts/build-local-schema.mjs from fico-api/supabase/migrations. Do not edit.
`
const prelude = splitSql(readFileSync(join('scripts', 'local-prelude.sql'), 'utf8'))
const extras = splitSql(readFileSync(join('scripts', 'local-extras.sql'), 'utf8'))
// Changes whenever the SQL does, so a device with an older local copy knows to rebuild it.
const version = createHash('sha1').update(JSON.stringify([prelude, statements, extras])).digest('hex').slice(0, 12)
writeFileSync(
  OUT,
  `${header}export const LOCAL_SCHEMA_VERSION = '${version}'
export const LOCAL_PRELUDE_STATEMENTS: string[] = ${JSON.stringify(prelude, null, 1)}
export const LOCAL_SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 1)}
export const LOCAL_EXTRAS_STATEMENTS: string[] = ${JSON.stringify(extras, null, 1)}
`
)
console.log(`[local-schema] wrote ${statements.length} schema statements (version ${version}) to ${OUT}`)
